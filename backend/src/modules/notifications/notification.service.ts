let ensureSchemaPromise: Promise<void> | null = null;

async function ensureNotificationSchema() {
    if (!ensureSchemaPromise) {
        ensureSchemaPromise = (async () => {
            await db.execute(sql`
                create table if not exists notifications (
                    notification_id integer generated by default as identity primary key,
                    title text not null,
                    message text not null,
                    module text not null,
                    action text not null,
                    entity_id text,
                    route text,
                    target_role_ids jsonb not null default '[]'::jsonb,
                    target_role_names jsonb not null default '[]'::jsonb,
                    selection_mode text not null default 'auto',
                    actor_user_id integer references users(user_id) on delete set null,
                    actor_name text not null,
                    actor_role_id integer,
                    actor_role_name text,
                    created_at timestamptz not null default now()
                )
            `);
            await db.execute(sql`
                create index if not exists notifications_created_idx
                on notifications(created_at desc)
            `);
            await db.execute(sql`
                create index if not exists notifications_target_roles_gin_idx
                on notifications using gin (target_role_ids)
            `);
            await db.execute(sql`
                create table if not exists notification_reads (
                    notification_id integer not null references notifications(notification_id) on delete cascade,
                    user_id integer not null references users(user_id) on delete cascade,
                    read_at timestamptz not null default now(),
                    primary key (notification_id, user_id)
                )
            `);
            await db.execute(sql`
                create index if not exists notification_reads_user_idx
                on notification_reads(user_id)
            `);
        })().catch((error) => {
            ensureSchemaPromise = null;
            throw error;
        });
    }
    return ensureSchemaPromise;
}

function toNotificationDto(
    row: typeof notifications.$inferSelect,
    isRead: boolean,
): RoleNotificationDto {
    return {
        notificationId: row.notificationId,
        title: row.title,
        message: row.message,
        module: row.module,
        action: row.action,
        entityId: row.entityId,
        route: row.route,
        targetRoleIds: Array.isArray(row.targetRoleIds) ? row.targetRoleIds : [],
        targetRoleNames: Array.isArray(row.targetRoleNames) ? row.targetRoleNames : [],
        selectionMode:
            row.selectionMode === 'custom' || row.selectionMode === 'manual'
                ? row.selectionMode
                : 'auto',
        actorUserId: row.actorUserId,
        actorName: row.actorName,
        actorRoleId: row.actorRoleId,
        actorRoleName: row.actorRoleName,
        createdAt: row.createdAt.toISOString(),
        isRead,
    };
}

const ROLE_CACHE_TTL_MS = 30_000;
let roleCache: { expiresAt: number; value: Promise<RoleSummary[]> } | null = null;

function invalidateRoleCache() {
    roleCache = null;
}

export async function listNotificationRoles(): Promise<RoleSummary[]> {
    const now = Date.now();
    if (roleCache && roleCache.expiresAt > now) return roleCache.value;
    const value = db
        .select({
            roleId: roles.roleId,
            name: roles.name,
            description: roles.description,
            settings: roles.settings,
        })
        .from(roles)
        .orderBy(asc(roles.name), asc(roles.roleId));
    roleCache = { expiresAt: now + ROLE_CACHE_TTL_MS, value };
    value.catch(() => {
        if (roleCache?.value === value) roleCache = null;
    });
    return value;
}

export async function listRoleNotifications(
    userId: number,
    roleId: number,
    query: ListNotificationsQuery = {},
): Promise<{ items: RoleNotificationDto[]; unreadCount: number }> {
    await ensureNotificationSchema();
    const limit = query.limit ?? 40;
    const roleFilter = sql`${notifications.targetRoleIds} @> ${JSON.stringify([roleId])}::jsonb`;

    const [rows, countRows] = await Promise.all([
        db
            .select({
                notification: notifications,
                readAt: notificationReads.readAt,
            })
            .from(notifications)
            .leftJoin(
                notificationReads,
                and(
                    eq(notificationReads.notificationId, notifications.notificationId),
                    eq(notificationReads.userId, userId),
                ),
            )
            .where(query.unreadOnly ? and(roleFilter, isNull(notificationReads.readAt)) : roleFilter)
            .orderBy(desc(notifications.createdAt), desc(notifications.notificationId))
            .limit(limit),

        db
            .select({ count: sql<number>`count(*)::int` })
            .from(notifications)
            .leftJoin(
                notificationReads,
                and(
                    eq(notificationReads.notificationId, notifications.notificationId),
                    eq(notificationReads.userId, userId),
                ),
            )
            .where(and(roleFilter, isNull(notificationReads.readAt))),
    ]);

    return {
        items: rows.map((entry) => toNotificationDto(entry.notification, Boolean(entry.readAt))),
        unreadCount: countRows[0]?.count ?? 0,
    };
}

export async function createManualNotification(
    input: SendNotificationInput,
    actor: {
        userId: number;
        firstName: string;
        lastName: string;
        roleId: number;
    },
): Promise<RoleNotificationDto> {
    await ensureNotificationSchema();
    const uniqueTargetIds = [...new Set(input.targetRoleIds)];

    const matchedRoles = await db
        .select({
            roleId: roles.roleId,
            name: roles.name,
        })
        .from(roles)
        .where(inArray(roles.roleId, uniqueTargetIds))
        .orderBy(asc(roles.name));

    if (matchedRoles.length === 0) {
        throw new AppError(400, 'Select at least one valid role to notify.');
    }

    const [actorRole] = await db
        .select({ name: roles.name })
        .from(roles)
        .where(eq(roles.roleId, actor.roleId))
        .limit(1);

    const actorName = `${actor.firstName} ${actor.lastName}`.trim() || 'User';

    const [inserted] = await db
        .insert(notifications)
        .values({
            title: input.title,
            message: input.message,
            module: 'manual',
            action: 'manual',
            entityId: null,
            route: input.route ?? null,
            targetRoleIds: matchedRoles.map((r) => r.roleId),
            targetRoleNames: matchedRoles.map((r) => r.name),
            selectionMode: 'manual',
            actorUserId: actor.userId,
            actorName,
            actorRoleId: actor.roleId,
            actorRoleName: actorRole?.name ?? null,
        })
        .returning();

    const dto = toNotificationDto(inserted!, false);
    emitRoleNotification(dto);
    return dto;
}

export async function markNotificationRead(
    notificationId: number,
    userId: number,
    roleId: number,
): Promise<void> {
    await ensureNotificationSchema();
    const roleFilter = sql`${notifications.targetRoleIds} @> ${JSON.stringify([roleId])}::jsonb`;
    const [existing] = await db
        .select({ notificationId: notifications.notificationId })
        .from(notifications)
        .where(and(eq(notifications.notificationId, notificationId), roleFilter))
        .limit(1);

    if (!existing) {
        throw new AppError(404, 'Notification not found for your role.');
    }

    await db
        .insert(notificationReads)
        .values({ notificationId, userId })
        .onConflictDoNothing();
}

export async function markAllNotificationsRead(userId: number, roleId: number): Promise<void> {
    await ensureNotificationSchema();
    const roleFilter = sql`${notifications.targetRoleIds} @> ${JSON.stringify([roleId])}::jsonb`;
    const unreadRows = await db
        .select({ notificationId: notifications.notificationId })
        .from(notifications)
        .leftJoin(
            notificationReads,
            and(
                eq(notificationReads.notificationId, notifications.notificationId),
                eq(notificationReads.userId, userId),
            ),
        )
        .where(and(roleFilter, isNull(notificationReads.readAt)));

    if (unreadRows.length === 0) return;

    await db
        .insert(notificationReads)
        .values(unreadRows.map((row) => ({ notificationId: row.notificationId, userId })))
        .onConflictDoNothing();
}

export async function recordMutationSyncAndNotification(input: {
    method: string;
    path: string;
    actor: {
        userId: number;
        firstName: string;
        lastName: string;
        roleId: number;
    };
    notifySelection: NotifyHeaderSelection;
    originSocketId?: string | null;
}): Promise<void> {
    const context = resolveMutationContext(input.method, input.path);
    const actorName = `${input.actor.firstName} ${input.actor.lastName}`.trim() || 'User';
    const timestamp = new Date().toISOString();

    // Sync operational data updates to ALL connected users & roles immediately.
    // The originating tab already refreshed its own cache after the request.
    emitDataSync(
        {
            eventId: randomUUID(),
            module: context.module,
            action: context.action,
            method: input.method,
            path: input.path.split('?')[0] ?? input.path,
            entityId: context.entityId,
            queryKeys: context.queryKeys,
            actorUserId: input.actor.userId,
            actorName,
            actorRoleId: input.actor.roleId,
            timestamp,
        },
        { excludeSocketId: input.originSocketId },
    );

    // Role/permission or account changes affect who belongs to which role room.
    if (context.module === 'roles' || context.module === 'users') {
        invalidateRoleCache();
        void refreshRealtimeMemberships();
    }

    if (input.notifySelection.mode === 'none') {
        return;
    }

    await ensureNotificationSchema();
    const allRoles = await listNotificationRoles();
    const targetRoles = resolveTargetRoleIds(
        allRoles,
        input.notifySelection,
        context.recommendedPermissions,
        context.notificationTag,
    );

    if (targetRoles.length === 0) {
        return;
    }

    const actorRole = allRoles.find((role) => role.roleId === input.actor.roleId);
    const { title, message } = formatActionSentence(
        actorName,
        context.label,
        context.action,
        context.entityId,
        input.notifySelection.note,
    );

    const [inserted] = await db
        .insert(notifications)
        .values({
            title,
            message,
            module: context.module,
            action: context.action,
            entityId: context.entityId,
            route: context.route,
            targetRoleIds: targetRoles.map((role) => role.roleId),
            targetRoleNames: targetRoles.map((role) => role.name),
            selectionMode: input.notifySelection.mode,
            actorUserId: input.actor.userId,
            actorName,
            actorRoleId: input.actor.roleId,
            actorRoleName: actorRole?.name ?? null,
        })
        .returning();

    if (inserted) {
        emitRoleNotification(toNotificationDto(inserted, false));
    }
}
