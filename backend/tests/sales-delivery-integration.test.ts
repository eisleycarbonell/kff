test(
    'sales and delivery PostgreSQL operations protect orders, lots, transit stock and atomic fulfillment',
    { skip: !testDatabaseUrl, timeout: 600_000 },
    async (context) => {
        assert.ok(testDatabaseUrl);
        const schemaName = 'sales_delivery_test_' + randomBytes(8).toString('hex');
        assert.match(schemaName, /^sales_delivery_test_[a-f0-9]+$/);
        const admin = postgres(testDatabaseUrl, {
            max: 1,
            connect_timeout: 10,
            onnotice: () => {},
        });
        const client = postgres(testDatabaseUrl, {
            max: 6,
            connect_timeout: 10,
            connection: { search_path: schemaName, statement_timeout: 60000 },
            onnotice: () => {},
        });
        let schemaCreated = false;
        try {
            await admin.unsafe('create schema "' + schemaName + '"');
            schemaCreated = true;
            const [current] =
                await client.unsafe<{ current_schema: string }[]>('select current_schema()');
            assert.equal(current?.current_schema, schemaName);
            await client.unsafe(baseFixtureSql);
            await client.unsafe(extensionSql);
            const database = drizzle({ client });
            const sales = await import('../src/modules/sales-orders/sales-order.service.ts');
            const deliveries =
                await import('../src/modules/delivery-orders/delivery-order.service.ts');
            const transfers = await import('../src/modules/transfers/transfer.service.ts');
            const createOrder = async (number: string, quantity = '10') => {
                const order = await sales.createSalesOrder(
                    {
                        salesOrderNumber: number,
                        customerId: 1,
                        orderDate: '2026-11-05',
                        lines: [{ itemId: 1, uomId: 1, qtyOrdered: quantity, unitPrice: '2.5' }],
                    },
                    1,
                    database,
                );
                const confirmed = await sales.confirmSalesOrder(order.salesOrderId, 1, database);
                assert.ok(confirmed);
                return confirmed;
            };
            type Order = Awaited<ReturnType<typeof createOrder>>;
            const createDelivery = (number: string, order: Order, quantity = '5', lotId = 1) =>
                deliveries.createDeliveryOrder(
                    {
                        deliveryOrderNumber: number,
                        salesOrderId: order.salesOrderId,
                        sourceLocationId: 1,
                        deliveryDate: '2026-11-06',
                        lines: [
                            {
                                salesOrderLineId: order.lines[0]!.salesOrderLineId,
                                lotId,
                                qtyDelivered: quantity,
                            },
                        ],
                    },
                    1,
                    database,
                );
            const dispatch = (id: number) =>
                deliveries.dispatchDeliveryOrder(id, { transitLocationId: 3 }, 1, database);
            async function state() {
                return Promise.all(
                    [
                        'sales_orders',
                        'sales_order_lines',
                        'delivery_orders',
                        'delivery_order_lines',
                        'inventory_stock',
                        'inventory_transactions',
                        'inventory_reservations',
                    ].map(async (table) => ({
                        table,
                        rows: Array.from(
                            await client.unsafe('select * from ' + table + ' order by 1'),
                        ),
                    })),
                );
            }
            async function balanced() {
                const mismatches = await client.unsafe(
                    'select stock.stock_id from inventory_stock stock left join inventory_transactions entry on entry.lot_id=stock.lot_id and entry.item_id=stock.item_id and entry.location_id=stock.location_id group by stock.stock_id having stock.qty_on_hand<>coalesce(sum(entry.qty_change),0)',
                );
                assert.equal(mismatches.length, 0);
            }
            async function run(name: string, action: () => Promise<void>) {
                await context.test(name, async () => {
                    await client.unsafe(resetSql);
                    await action();
                });
            }
            await run(
                'partial and final deliveries preserve lot provenance, ledger balances and sales fulfillment',
                async () => {
                    const order = await createOrder('SO-FULFILL');
                    assert.equal(order.totalAmount, '25.0000');
                    const before = await client.unsafe(
                        'select * from inventory_stock order by stock_id',
                    );
                    const first = await createDelivery('DO-PARTIAL', order);
                    assert.deepEqual(
                        await client.unsafe('select * from inventory_stock order by stock_id'),
                        before,
                    );
                    await dispatch(first.deliveryOrderId);
                    let savedOrder = await sales.getSalesOrder(order.salesOrderId, database);
                    assert.equal(savedOrder?.lines[0]?.qtyDelivered, '0.0000');
                    assert.equal(savedOrder?.lines[0]?.qtyAllocated, '5.0000');
                    const transitRows = await client.unsafe(
                        'select qty_on_hand from inventory_stock where lot_id=1 and location_id=3',
                    );
                    assert.equal(transitRows[0]?.qty_on_hand, '5.0000');
                    await deliveries.completeDeliveryOrder(first.deliveryOrderId, 1, database);
                    savedOrder = await sales.getSalesOrder(order.salesOrderId, database);
                    assert.equal(savedOrder?.status, 'Partially Delivered');
                    assert.equal(savedOrder?.lines[0]?.qtyRemaining, '5.0000');
                    const second = await createDelivery('DO-FINAL', order);
                    await dispatch(second.deliveryOrderId);
                    await deliveries.completeDeliveryOrder(second.deliveryOrderId, 1, database);
                    savedOrder = await sales.getSalesOrder(order.salesOrderId, database);
                    assert.equal(savedOrder?.status, 'Completed');
                    assert.equal(savedOrder?.lines[0]?.qtyDelivered, '10.0000');
                    const trace = await client.unsafe(
                        "select txn.delivery_order_line_id,txn.authorized_by_user_id,lots.packing_order_id from inventory_transactions txn join lots using(lot_id) where txn.transaction_type='Sale'",
                    );
                    assert.equal(trace.length, 2);
                    assert.ok(
                        trace.every(
                            (row) =>
                                row.delivery_order_line_id &&
                                row.packing_order_id === 1 &&
                                row.authorized_by_user_id === 1,
                        ),
                    );
                    await balanced();
                    const finalState = await state();
                    await assert.rejects(dispatch(first.deliveryOrderId), { status: 409 });
                    await assert.rejects(
                        deliveries.completeDeliveryOrder(first.deliveryOrderId, 1, database),
                        { status: 409 },
                    );
                    await assert.rejects(
                        deliveries.cancelDeliveryOrder(first.deliveryOrderId, 1, database),
                        { status: 409 },
                    );
                    assert.deepEqual(await state(), finalState);
                },
            );
            await run('concurrent delivery allocations cannot exceed one sales order', async () => {
                const order = await createOrder('SO-ALLOCATION');
                const results = await Promise.allSettled([
                    createDelivery('DO-A', order, '7'),
                    createDelivery('DO-B', order, '7'),
                ]);
                assert.equal(results.filter((row) => row.status === 'fulfilled').length, 1);
                const failure = results.find((row) => row.status === 'rejected');
                assert.ok(failure && failure.status === 'rejected');
                assert.equal(failure.reason.status, 409);
                const saved = await sales.getSalesOrder(order.salesOrderId, database);
                assert.equal(saved?.lines[0]?.qtyAllocated, '7.0000');
            });
            await run(
                'concurrent dispatches respect source availability and active packing reservations',
                async () => {
                    await client.unsafe(
                        'insert into inventory_reservations(packing_order_material_id,item_id,lot_id,location_id,qty_reserved) values(1,1,1,1,5)',
                    );
                    const first = await createDelivery(
                        'DO-STOCK-A',
                        await createOrder('SO-STOCK-A'),
                        '10',
                    );
                    const second = await createDelivery(
                        'DO-STOCK-B',
                        await createOrder('SO-STOCK-B'),
                        '10',
                    );
                    const results = await Promise.allSettled([
                        dispatch(first.deliveryOrderId),
                        dispatch(second.deliveryOrderId),
                    ]);
                    assert.equal(results.filter((row) => row.status === 'fulfilled').length, 1);
                    const rejected = results.find((row) => row.status === 'rejected');
                    assert.ok(rejected && rejected.status === 'rejected');
                    assert.equal(rejected.reason.status, 409);
                    const [balance] = await client.unsafe(
                        'select qty_on_hand from inventory_stock where lot_id=1 and location_id=1',
                    );
                    assert.equal(balance?.qty_on_hand, '10.0000');
                    await balanced();
                },
            );
            await run(
                'transit reservations prevent another transfer from consuming delivery stock',
                async () => {
                    const order = await createOrder('SO-PROTECTED');
                    const delivery = await createDelivery('DO-PROTECTED', order, '10');
                    await dispatch(delivery.deliveryOrderId);
                    const transfer = await transfers.createTransfer(
                        {
                            transferNumber: 'TR-PROTECTED',
                            sourceLocationId: 1,
                            destinationLocationId: 2,
                            lines: [{ itemId: 1, lotId: 1, qtyRequested: '5' }],
                        },
                        1,
                        database,
                    );
                    await transfers.dispatchTransfer(
                        transfer.transferId,
                        {
                            transitLocationId: 3,
                            lines: [
                                {
                                    transferLineId: transfer.lines[0]!.transferLineId,
                                    qtyShipped: '5',
                                },
                            ],
                        },
                        1,
                        database,
                    );
                    // Simulate a damaged transit balance: the other shipment's reservation must still be protected.
                    await client.unsafe(
                        'update inventory_stock set qty_on_hand=14 where lot_id=1 and location_id=3',
                    );
                    await assert.rejects(
                        transfers.receiveTransfer(
                            transfer.transferId,
                            {
                                lines: [
                                    {
                                        transferLineId: transfer.lines[0]!.transferLineId,
                                        qtyReceived: '5',
                                    },
                                ],
                            },
                            1,
                            database,
                        ),
                        { status: 409 },
                    );
                    await client.unsafe(
                        'update inventory_stock set qty_on_hand=15 where lot_id=1 and location_id=3',
                    );
                    await deliveries.completeDeliveryOrder(delivery.deliveryOrderId, 1, database);
                    await transfers.receiveTransfer(
                        transfer.transferId,
                        {
                            lines: [
                                {
                                    transferLineId: transfer.lines[0]!.transferLineId,
                                    qtyReceived: '5',
                                },
                            ],
                        },
                        1,
                        database,
                    );
                    await balanced();
                },
            );
            await run(
                'failed dispatch and completion ledger writes roll back every related table',
                async () => {
                    const order = await createOrder('SO-ROLLBACK');
                    const delivery = await createDelivery('DO-ROLLBACK', order);
                    await client.unsafe(
                        "create function reject_delivery_ledger() returns trigger language plpgsql as $$ begin raise exception 'simulated ledger failure'; end $$; create trigger reject_ledger before insert on inventory_transactions for each row execute function reject_delivery_ledger()",
                    );
                    const beforeDispatch = await state();
                    await assert.rejects(
                        dispatch(delivery.deliveryOrderId),
                        (error: unknown) => getDatabaseErrorCode(error) === 'P0001',
                    );
                    assert.deepEqual(await state(), beforeDispatch);
                    await client.unsafe('drop trigger reject_ledger on inventory_transactions');
                    await dispatch(delivery.deliveryOrderId);
                    await client.unsafe(
                        'create trigger reject_ledger before insert on inventory_transactions for each row execute function reject_delivery_ledger()',
                    );
                    const beforeComplete = await state();
                    await assert.rejects(
                        deliveries.completeDeliveryOrder(delivery.deliveryOrderId, 1, database),
                        (error: unknown) => getDatabaseErrorCode(error) === 'P0001',
                    );
                    assert.deepEqual(await state(), beforeComplete);
                    await client.unsafe(
                        'drop trigger reject_ledger on inventory_transactions; drop function reject_delivery_ledger()',
                    );
                },
            );
            await run(
                'draft cancellation frees order allocation and invalid lots and transitions are rejected',
                async () => {
                    const order = await createOrder('SO-CANCEL');
                    const delivery = await createDelivery('DO-CANCEL', order, '10');
                    await assert.rejects(sales.cancelSalesOrder(order.salesOrderId, 1, database), {
                        status: 409,
                    });
                    await deliveries.cancelDeliveryOrder(delivery.deliveryOrderId, 1, database);
                    const saved = await sales.getSalesOrder(order.salesOrderId, database);
                    assert.equal(saved?.lines[0]?.qtyAllocated, '0.0000');
                    for (const lotId of [3, 4, 5, 6])
                        await assert.rejects(createDelivery('DO-BAD-' + lotId, order, '5', lotId));
                    const valid = await createDelivery('DO-RECHECK', order);
                    await client.unsafe("update lots set qc_status='Rejected' where lot_id=1");
                    await assert.rejects(dispatch(valid.deliveryOrderId), { status: 409 });
                    await deliveries.cancelDeliveryOrder(valid.deliveryOrderId, 1, database);
                    await sales.cancelSalesOrder(order.salesOrderId, 1, database);
                    await assert.rejects(createDelivery('DO-CANCELLED-SALES', order), {
                        status: 409,
                    });
                    await balanced();
                },
            );
        } finally {
            await client.end({ timeout: 5 });
            try {
                if (schemaCreated) await admin.unsafe('drop schema "' + schemaName + '" cascade');
            } finally {
                await admin.end({ timeout: 5 });
            }
        }
    },
);
