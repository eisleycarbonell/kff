test(
    'packing PostgreSQL transactions enforce concurrent reservations, historical snapshots and atomic completion',
    { skip: !testDatabaseUrl, timeout: 60_000 },
    async (context) => {
        assert.ok(testDatabaseUrl);
        const schemaName = 'packing_test_' + process.pid + '_' + randomBytes(8).toString('hex');
        assert.match(schemaName, /^packing_test_[a-z0-9_]+$/);
        const admin = postgres(testDatabaseUrl, {
            max: 1,
            connect_timeout: 10,
            onnotice: () => {},
        });
        const client = postgres(testDatabaseUrl, {
            max: 6,
            connect_timeout: 10,
            connection: { search_path: schemaName, statement_timeout: 15_000 },
            onnotice: () => {},
        });
        let schemaCreated = false;
        try {
            await admin.unsafe('create schema "' + schemaName + '"');
            schemaCreated = true;
            const [current] =
                await client.unsafe<{ current_schema: string }[]>('select current_schema()');
            assert.equal(current?.current_schema, schemaName);
            await client.unsafe(fixtureSql);
            const database = drizzle({ client });
            const service = await import('../src/modules/packing-orders/packing-order.service.ts');
            const input = {
                itemId: 3,
                targetQty: '10',
                sourceLocationId: 1,
                destinationLocationId: 2,
            };
            const first = await service.createPackingOrder(
                { ...input, packingOrderNumber: 'PK-TEST-1' },
                1,
                database,
            );
            const second = await service.createPackingOrder(
                { ...input, packingOrderNumber: 'PK-TEST-2' },
                1,
                database,
            );
            const snapshots = [first, second];
            for (const order of snapshots) {
                assert.equal(order.status, 'Draft');
                assert.equal(order.createdBy, 1);
                assert.deepEqual(
                    order.materials.map((material) => ({
                        itemId: material.itemId,
                        uomId: material.uomId,
                        requiredQty: material.requiredQty,
                    })),
                    [
                        { itemId: 1, uomId: 1, requiredQty: '1.0000' },
                        { itemId: 2, uomId: 3, requiredQty: '10.0000' },
                    ],
                );
            }

            async function operationalState() {
                const tables = [
                    ['packing_orders', 'packing_order_id'],
                    ['packing_order_materials', 'packing_order_material_id'],
                    ['inventory_reservations', 'reservation_id'],
                    ['inventory_stock', 'stock_id'],
                    ['inventory_transactions', 'transaction_id'],
                    ['lots', 'lot_id'],
                ] as const;
                return Promise.all(
                    tables.map(async ([table, key]) => ({
                        table,
                        rows: await client.unsafe('select * from ' + table + ' order by ' + key),
                    })),
                );
            }

            let winnerId = 0;
            let loserId = 0;
            await context.test(
                'two real concurrent plans cannot promise the same stock',
                async () => {
                    const planned = await Promise.allSettled(
                        snapshots.map((order) =>
                            service.planPackingOrder(order.packingOrderId, 1, database),
                        ),
                    );
                    const successful = planned.filter((result) => result.status === 'fulfilled');
                    const rejected = planned.filter((result) => result.status === 'rejected');
                    assert.equal(successful.length, 1);
                    assert.equal(rejected.length, 1);
                    assert.ok(rejected[0]!.reason instanceof AppError);
                    assert.equal(rejected[0]!.reason.status, 409);
                    const winner = successful[0]!.value;
                    assert.ok(winner);
                    winnerId = winner.packingOrderId;
                    loserId = snapshots.find(
                        (order) => order.packingOrderId !== winnerId,
                    )!.packingOrderId;
                    assert.equal(winner.status, 'Planned');
                    assert.equal(
                        (await service.getPackingOrder(loserId, database))?.status,
                        'Draft',
                    );
                    assert.deepEqual(
                        Array.from(
                            await client.unsafe(
                                'select item_id, sum(qty_reserved - qty_consumed)::numeric(14,4)::text as outstanding ' +
                                    'from inventory_reservations where released_at is null group by item_id order by item_id',
                            ),
                        ),
                        [
                            { item_id: 1, outstanding: '1.0000' },
                            { item_id: 2, outstanding: '10.0000' },
                        ],
                    );
                    const loser = await service.getPackingOrder(loserId, database);
                    assert.equal(loser?.reservations.length, 0);
                    const [ledger] = await client.unsafe<{ count: number }[]>(
                        'select count(*)::integer as count from inventory_transactions',
                    );
                    assert.equal(ledger?.count, 2);
                },
            );

            await context.test('later BOM edits do not rewrite existing requirements', async () => {
                await client.unsafe(
                    'update bill_of_materials set quantity = 200 where component_item_id = 1',
                );
                const preview = await service.previewPackingOrder(input, database);
                assert.equal(
                    preview.materials.find((row) => row.itemId === 1)?.requiredQty,
                    '2.0000',
                );
                const historical = await service.getPackingOrder(winnerId, database);
                assert.equal(
                    historical?.materials.find((row) => row.itemId === 1)?.requiredQty,
                    '1.0000',
                );
                await service.startPackingOrder(winnerId, 1, database);
            });

            await context.test(
                'duplicate finished lot rolls back every consumption and reservation write',
                async () => {
                    const before = await operationalState();
                    await assert.rejects(
                        service.completePackingOrder(
                            winnerId,
                            { actualQty: '6', lotNumber: 'EXISTING-LOT' },
                            1,
                            database,
                        ),
                        (error: unknown) => getDatabaseErrorCode(error) === '23505',
                    );
                    assert.deepEqual(await operationalState(), before);
                },
            );

            await context.test(
                'failure after finished stock creation also rolls back all operational records',
                async () => {
                    await client.unsafe(
                        'create function fail_packing_production() returns trigger language plpgsql as $$ ' +
                            "begin if new.transaction_type = 'Produce' then " +
                            "raise exception 'packing integration output failure'; end if; return new; end; $$; " +
                            'create trigger packing_output_failure before insert on inventory_transactions ' +
                            'for each row execute function fail_packing_production()',
                    );
                    try {
                        const before = await operationalState();
                        await assert.rejects(
                            service.completePackingOrder(
                                winnerId,
                                { actualQty: '6', lotNumber: 'FAILED-OUTPUT' },
                                1,
                                database,
                            ),
                            (error: unknown) => getDatabaseErrorCode(error) === 'P0001',
                        );
                        assert.deepEqual(await operationalState(), before);
                    } finally {
                        await client.unsafe(
                            'drop trigger packing_output_failure on inventory_transactions; drop function fail_packing_production()',
                        );
                    }
                },
            );

            await context.test(
                'completion consumes the snapshot, releases unused reservations and balances its ledger',
                async () => {
                    const completed = await service.completePackingOrder(
                        winnerId,
                        {
                            actualQty: '6',
                            lotNumber: 'FG-OUTPUT',
                            manufactureDate: null,
                            expirationDate: null,
                        },
                        1,
                        database,
                    );
                    assert.ok(completed);
                    assert.equal(completed.status, 'Completed');
                    assert.equal(completed.actualQty, '6.0000');
                    assert.equal(completed.updatedBy, 1);
                    assert.ok(completed.startedAt);
                    assert.ok(completed.completedAt);
                    assert.deepEqual(
                        completed.materials.map((row) => row.consumedQty),
                        ['0.6000', '6.0000'],
                    );
                    assert.ok(
                        completed.reservations.every(
                            (row) => row.releasedAt !== null && row.qtyOutstanding === '0.0000',
                        ),
                    );
                    assert.deepEqual(completed.reservations.map((row) => row.qtyConsumed).sort(), [
                        '0.6000',
                        '6.0000',
                    ]);
                    const [output] = await client.unsafe(
                        'select item_id, po_line_id, packing_order_id, manufacture_date, expiration_date, ' +
                            "qc_status, unit_cost::text, created_by, updated_by from lots where lot_number = 'FG-OUTPUT'",
                    );
                    assert.deepEqual(output, {
                        item_id: 3,
                        po_line_id: null,
                        packing_order_id: winnerId,
                        manufacture_date: null,
                        expiration_date: null,
                        qc_status: 'Approved',
                        unit_cost: '1.5000',
                        created_by: 1,
                        updated_by: 1,
                    });
                    const ledger = Array.from(
                        await client.unsafe(
                            'select transaction_type, item_id, location_id, qty_change::text, packing_order_id, ' +
                                'authorized_by_user_id from inventory_transactions where packing_order_id = ' +
                                winnerId +
                                ' order by item_id',
                        ),
                    );
                    assert.deepEqual(ledger, [
                        {
                            transaction_type: 'Consume',
                            item_id: 1,
                            location_id: 1,
                            qty_change: '-0.6000',
                            packing_order_id: winnerId,
                            authorized_by_user_id: 1,
                        },
                        {
                            transaction_type: 'Consume',
                            item_id: 2,
                            location_id: 1,
                            qty_change: '-6.0000',
                            packing_order_id: winnerId,
                            authorized_by_user_id: 1,
                        },
                        {
                            transaction_type: 'Produce',
                            item_id: 3,
                            location_id: 2,
                            qty_change: '6.0000',
                            packing_order_id: winnerId,
                            authorized_by_user_id: 1,
                        },
                    ]);
                    const balances = Array.from(
                        await client.unsafe(
                            'select stock.item_id, stock.location_id, stock.qty_on_hand::text, ' +
                                'coalesce(sum(entry.qty_change), 0)::numeric(14,4)::text as ledger_qty ' +
                                'from inventory_stock stock left join inventory_transactions entry ' +
                                'on entry.item_id = stock.item_id and entry.lot_id = stock.lot_id and entry.location_id = stock.location_id ' +
                                'group by stock.stock_id order by stock.item_id',
                        ),
                    );
                    assert.deepEqual(balances, [
                        { item_id: 1, location_id: 1, qty_on_hand: '0.9000', ledger_qty: '0.9000' },
                        { item_id: 2, location_id: 1, qty_on_hand: '9.0000', ledger_qty: '9.0000' },
                        { item_id: 3, location_id: 2, qty_on_hand: '6.0000', ledger_qty: '6.0000' },
                    ]);
                    const before = await operationalState();
                    await assert.rejects(
                        service.completePackingOrder(
                            winnerId,
                            { actualQty: '6', lotNumber: 'DUPLICATE-COMPLETION' },
                            1,
                            database,
                        ),
                        (error: unknown) => error instanceof AppError && error.status === 409,
                    );
                    await assert.rejects(
                        service.startPackingOrder(winnerId, 1, database),
                        (error: unknown) => error instanceof AppError && error.status === 409,
                    );
                    assert.deepEqual(await operationalState(), before);
                },
            );

            await context.test(
                'cancelling an in-progress order releases stock without ledger changes',
                async () => {
                    await client.unsafe(
                        'update bill_of_materials set quantity = 100 where component_item_id = 1',
                    );
                    const order = await service.createPackingOrder(
                        { ...input, targetQty: '5', packingOrderNumber: 'PK-TEST-CANCEL' },
                        1,
                        database,
                    );
                    await service.planPackingOrder(order.packingOrderId, 1, database);
                    await service.startPackingOrder(order.packingOrderId, 1, database);
                    const stockBefore = await client.unsafe(
                        'select * from inventory_stock order by stock_id',
                    );
                    const ledgerBefore = await client.unsafe(
                        'select * from inventory_transactions order by transaction_id',
                    );
                    const cancelled = await service.cancelPackingOrder(
                        order.packingOrderId,
                        1,
                        database,
                    );
                    assert.equal(cancelled?.status, 'Cancelled');
                    assert.ok(
                        cancelled?.reservations.every(
                            (row) =>
                                row.releasedAt !== null &&
                                row.qtyConsumed === '0.0000' &&
                                row.qtyOutstanding === '0.0000',
                        ),
                    );
                    assert.deepEqual(
                        await client.unsafe('select * from inventory_stock order by stock_id'),
                        stockBefore,
                    );
                    assert.deepEqual(
                        await client.unsafe(
                            'select * from inventory_transactions order by transaction_id',
                        ),
                        ledgerBefore,
                    );
                },
            );
        } finally {
            try {
                await client.end({ timeout: 5 });
            } finally {
                try {
                    if (schemaCreated) {
                        // The validated generated name confines cleanup to this test schema.
                        await admin.unsafe('drop schema "' + schemaName + '" cascade');
                    }
                } finally {
                    await admin.end({ timeout: 5 });
                }
            }
        }
    },
);
