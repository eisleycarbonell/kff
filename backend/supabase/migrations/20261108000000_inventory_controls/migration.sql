-- Additive inventory controls and master data; existing operational history is preserved.
CREATE TABLE "company_settings" (
	"settings_id" integer PRIMARY KEY DEFAULT 1,
	"company_name" varchar(120) DEFAULT 'Kusina Filipino Food' NOT NULL,
	"address" text,
	"email" varchar(254),
	"phone" varchar(40),
	"currency_code" varchar(3) DEFAULT 'PHP' NOT NULL,
	"default_reorder_level" numeric(14,4) DEFAULT '10' NOT NULL,
	"expiry_warning_days" integer DEFAULT 30 NOT NULL,
	"version" integer DEFAULT 1 NOT NULL,
	"created_by" integer,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_by" integer,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "settings_singleton" CHECK ("settings_id"=1),
	CONSTRAINT "settings_limits" CHECK ("default_reorder_level">=0 and "expiry_warning_days" between 0 and 3650 and "version">0)
);

CREATE TABLE "count_observations" (
	"observation_id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "count_observations_observation_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"request_id" integer NOT NULL,
	"lot_id" integer NOT NULL,
	"expected_qty" numeric(14,4) NOT NULL,
	"counted_qty" numeric(14,4),
	"observed_by" integer,
	"observed_at" timestamp with time zone,
	CONSTRAINT "count_request_lot_uq" UNIQUE("request_id","lot_id"),
	CONSTRAINT "count_quantities_nonnegative" CHECK ("expected_qty">=0 and ("counted_qty" is null or "counted_qty">=0))
);

CREATE TABLE "count_sessions" (
	"request_id" integer PRIMARY KEY,
	"location_id" integer NOT NULL,
	"reason_id" integer NOT NULL
);

CREATE TABLE "formula_revision_materials" (
	"material_id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "formula_revision_materials_material_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"request_id" integer NOT NULL,
	"component_item_id" integer NOT NULL,
	"quantity" numeric(14,6) NOT NULL,
	"uom_id" integer NOT NULL,
	CONSTRAINT "formula_revision_component_uq" UNIQUE("request_id","component_item_id"),
	CONSTRAINT "formula_revision_qty_positive" CHECK ("quantity">0)
);

CREATE TABLE "formula_revisions" (
	"request_id" integer PRIMARY KEY,
	"item_id" integer NOT NULL,
	"revision_number" integer NOT NULL,
	"effective_date" date NOT NULL,
	"change_type" varchar(10) DEFAULT 'Replace' NOT NULL,
	CONSTRAINT "formula_revision_number_uq" UNIQUE("item_id","revision_number"),
	CONSTRAINT "formula_revision_valid" CHECK ("revision_number">0 and "change_type" in ('Replace','Retire'))
);

CREATE TABLE "inventory_disposals" (
	"request_id" integer PRIMARY KEY,
	"lot_id" integer NOT NULL,
	"source_location_id" integer NOT NULL,
	"destination_location_id" integer,
	"reason_id" integer NOT NULL,
	"quantity" numeric(14,4) NOT NULL,
	"expected_qty" numeric(14,4) NOT NULL,
	CONSTRAINT "disposal_qty_valid" CHECK ("quantity">0 and "expected_qty">=0),
	CONSTRAINT "disposal_locations_distinct" CHECK ("destination_location_id" is null or "destination_location_id"<>"source_location_id")
);

CREATE TABLE "qc_decisions" (
	"request_id" integer PRIMARY KEY,
	"lot_id" integer NOT NULL,
	"previous_status" "qc_status_enum" NOT NULL,
	"new_status" "qc_status_enum" NOT NULL,
	CONSTRAINT "qc_status_changed" CHECK ("previous_status"<>"new_status")
);

CREATE TABLE "reorder_policies" (
	"item_id" integer PRIMARY KEY,
	"reorder_level" numeric(14,4) NOT NULL,
	"created_by" integer,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_by" integer,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "reorder_level_nonnegative" CHECK ("reorder_level">=0)
);

CREATE TABLE "review_events" (
	"event_id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "review_events_event_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"request_id" integer NOT NULL,
	"action" varchar(30) NOT NULL,
	"note" text NOT NULL,
	"details" jsonb DEFAULT '{}' NOT NULL,
	"actor_id" integer NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL
);

CREATE TABLE "review_requests" (
	"request_id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (sequence name "review_requests_request_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
	"request_number" varchar(40) NOT NULL UNIQUE,
	"kind" varchar(20) NOT NULL,
	"status" varchar(20) DEFAULT 'Draft' NOT NULL,
	"notes" text NOT NULL,
	"evidence_reference" text,
	"submitted_by" integer,
	"submitted_at" timestamp with time zone,
	"reviewed_by" integer,
	"reviewed_at" timestamp with time zone,
	"review_note" text,
	"created_by" integer NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_by" integer,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "review_kind_valid" CHECK ("kind" in ('Count','Scrap','Disposition','QC','Formula')),
	CONSTRAINT "review_status_valid" CHECK ("status" in ('Draft','Submitted','Approved','Rejected','Cancelled')),
	CONSTRAINT "review_independent" CHECK ("reviewed_by" is null or ("reviewed_by"<>"created_by" and "reviewed_by"<>"submitted_by")),
	CONSTRAINT "review_approval_evidence" CHECK ("status"<>'Approved' or ("submitted_by" is not null and "submitted_at" is not null and "reviewed_by" is not null and "reviewed_at" is not null))
);
