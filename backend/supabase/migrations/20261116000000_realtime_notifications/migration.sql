create table if not exists notifications (
    notification_id integer generated by default as identity primary key,
    title text not null,
    message text not null,
    module text not null,
    action text not null,
    entity_id text,
    route text,
    target_role_ids jsonb not null default '[]'::jsonb,
    target_role_names jsonb not null default '[]'::jsonb,
    selection_mode text not null default 'auto',
    actor_user_id integer references users(user_id) on delete set null,
    actor_name text not null,
    actor_role_id integer,
    actor_role_name text,
    created_at timestamptz not null default now()
);

create index if not exists notifications_created_idx on notifications(created_at desc);
create index if not exists notifications_target_roles_gin_idx on notifications using gin (target_role_ids);

create table if not exists notification_reads (
    notification_id integer not null references notifications(notification_id) on delete cascade,
    user_id integer not null references users(user_id) on delete cascade,
    read_at timestamptz not null default now(),
    primary key (notification_id, user_id)
);

create index if not exists notification_reads_user_idx on notification_reads(user_id);
